// ─── Lookup helpers ───────────────────────────────────────────────────────────

export function getSubjectById(id) {
  return SUBJECTS.find(s => s.id === id) || null
}

export function getSubjectsByDomain(domain) {
  return SUBJECTS.filter(s => s.domain === domain)
}

export function getSubjectsByLayer(layer) {
  return SUBJECTS.filter(s => s.layer === layer)
}

export function getSubjectsByPhase(phase) {
  return SUBJECTS.filter(s => s.phase === phase)
}

export function getAvailableSubjects(completedIds = []) {
  return SUBJECTS.filter(s =>
    s.prerequisites.every(prereq => completedIds.includes(prereq))
  )
}

export function getPrerequisiteChain(subjectId, depth = 0) {
  if (depth > 10) return []
  const subject = getSubjectById(subjectId)
  if (!subject) return []

  const chain = []
  for (const prereqId of subject.prerequisites) {
    chain.push(prereqId)
    chain.push(...getPrerequisiteChain(prereqId, depth + 1))
  }
  return [...new Set(chain)]
}

